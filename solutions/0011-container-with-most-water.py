"""11. Container With Most Water (Medium) —— 专题：双指针

一句话：水量 = 短板的高度 × 两板距离。从两端开始夹逼，每次只移动【较短】的那块板。

为什么不能移动长板：起点宽度已是全场最大（n-1），之后每移动一次宽度必然 -1；
面积 = min(左右高) × 宽度，宽度只降，所以想变大只能靠高度变高，
而移动长板时短板原地不动 -> 高度被锁死、宽度还降了 -> 必然不更优。

为什么不会漏解：当 height[left] < height[right] 时，以 left 为左端点的所有容器，
宽度最大只有当前值、高度永远被 height[left] 锁死 -> 不可能超过当前答案
-> left 这个位置可以【永久排除】。每步排除一个位置，总步数 <= n。

时间 O(n)，空间 O(1)。

2026-10-02 AC 版本如下（末尾那个「、」是粘贴误触，入库时去掉，其余一字未改）。
"""

from typing import List


class Solution:
    def maxArea(self, height: List[int]) -> int:

        left, right = 0, len(height) - 1
        best = 0
        while left < right:
            best = max(best, min(height[left], height[right]) * (right - left))
            if height[left] < height[right]:
                left += 1            # 动短板：高度才有机会变高
            else:
                right -= 1
        return best


